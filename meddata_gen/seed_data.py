def random_datetime(start_str: str, end_str: str) -> datetime:
    """生成指定范围内的随机日期时间"""
    start = datetime.strptime(start_str, "%Y-%m-%d")
    end = datetime.strptime(end_str, "%Y-%m-%d")
    delta = end - start
    random_days = random.randint(0, delta.days)
    random_seconds = random.randint(0, 86399)
    return start + timedelta(days=random_days, seconds=random_seconds)


def maybe_null(value, null_rate: float = 0.05):
    """按概率返回NULL"""
    if random.random() < null_rate:
        return None
    return value


def maybe_empty(value, null_rate: float = 0.05):
    """按概率返回空字符串"""
    if random.random() < null_rate:
        return ""
    return value


def random_date_between(start: datetime, end: datetime):
    """两个datetime之间随机日期"""
    delta = end - start
    days = random.randint(0, max(delta.days, 0))
    return (start + timedelta(days=days)).date()
